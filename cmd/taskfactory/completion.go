// stdoutIsTerminal reports whether stdout is a character device.
func stdoutIsTerminal() bool {
	info, err := os.Stdout.Stat()
	return err == nil && info.Mode()&os.ModeCharDevice != 0
}

// completionCommand implements "taskfactory completion <shell>" and returns the
// exit code.
func completionCommand(args []string, stdout, stderr io.Writer, terminal bool) int {
	painter := ui.Painter{}
	fail := func(msg string) int {
		fmt.Fprintln(stderr, "taskfactory completion: "+msg)
		if line := nextOnFailure(painter, "completion", ""); line != "" {
			fmt.Fprintln(stderr, line)
		}
		return exitUsage
	}
	if len(args) == 0 {
		return fail("usage: taskfactory completion <bash|zsh>")
	}
	if len(args) > 1 {
		return fail(fmt.Sprintf("unexpected extra argument %q; usage: taskfactory completion <bash|zsh>", args[1]))
	}
	script, err := renderCompletionScript(args[0])
	if err != nil {
		return fail(err.Error())
	}
	fmt.Fprint(stdout, script)
	if terminal {
		if line := nextOnSuccess(painter, "completion", ""); line != "" {
			fmt.Fprintln(stderr, line)
		}
	}
	return 0
}

var completeIDPattern = regexp.MustCompile(`^(TF-[0-9]{3})-.*\.md$`)

// findRepoRoot walks up from dir to the first directory holding a .git entry.
// It reads no files and runs no subprocess.
func findRepoRoot(dir string) (string, bool) {
	for {
		if _, err := os.Lstat(filepath.Join(dir, ".git")); err == nil {
			return dir, true
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", false
		}
		dir = parent
	}
}

// completeHelper implements the hidden "__complete <kind> <command> [prefix]".
// It always exits 0 and prints nothing when it has nothing to offer.
func completeHelper(args []string, out io.Writer) int {
	if len(args) < 2 || args[0] != "ids" {
		return 0
	}
	spec, ok := findCompletionSpec(args[1])
	if !ok || !strings.HasPrefix(spec.Positional, "ids:") {
		return 0
	}
	prefix := ""
	if len(args) > 2 {
		prefix = args[2]
	}
	fields := strings.Fields(strings.TrimPrefix(spec.Positional, "ids:"))
	state := fields[0]
	needEvidence := len(fields) > 1 && fields[1] == "verified"
	cwd, err := os.Getwd()
	if err != nil {
		return 0
	}
	root, ok := findRepoRoot(cwd)
	if !ok {
		return 0
	}
	entries, err := os.ReadDir(filepath.Join(root, "tasks", state))
	if err != nil {
		return 0
	}
	var ids []string
	for _, e := range entries {
		m := completeIDPattern.FindStringSubmatch(e.Name())
		if m == nil || !strings.HasPrefix(m[1], prefix) {
			continue
		}
		if needEvidence {
			if _, err := os.Stat(filepath.Join(root, ".taskfactory", "evidence", m[1]+".jsonl")); err != nil {
				continue
			}
		}
		ids = append(ids, m[1])
	}
	sort.Strings(ids)
	for _, id := range ids {
		fmt.Fprintln(out, id)
	}
	return 0
}
