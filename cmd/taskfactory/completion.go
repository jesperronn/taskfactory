// completionFlag is one flag of a command. A flag takes no value, a value from
// the fixed Values list, or a free value that is not completed.
type completionFlag struct {
	Name   string
	Values []string
	Free   bool
}

func (f completionFlag) takesValue() bool { return f.Free || len(f.Values) > 0 }

// completionSpec describes the completion of one command. Positional is one of
// "none", "ids:<state>" (optionally "ids:<state> verified"), "path", "paths" or
// "words" (the fixed Words list).
type completionSpec struct {
	Command    string
	Positional string
	Words      []string
	Flags      []completionFlag
}

