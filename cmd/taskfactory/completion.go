// renderCompletionScript renders the script for shell, which is bash or zsh.
func renderCompletionScript(shell string) (string, error) {
	var t *template.Template
	switch shell {
	case "bash":
		t = bashTemplate
	case "zsh":
		t = zshTemplate
	default:
		return "", fmt.Errorf("unknown shell %q; usage: taskfactory completion <bash|zsh>", shell)
	}
	var b bytes.Buffer
	if err := t.Execute(&b, completionData()); err != nil {
		return "", err
	}
	return b.String(), nil
}

