// completionCommonFlags are offered for every command except completion.
var completionCommonFlags = []string{"--verbose", "--dry-run"}

func findCompletionSpec(command string) (completionSpec, bool) {
	for _, s := range completionSpecs {
		if s.Command == command {
			return s, true
		}
	}
	return completionSpec{}, false
}

// allFlags returns the flags offered for the command: its own, the common
// flags (except for completion) and --help.
func (s completionSpec) allFlags() []completionFlag {
	flags := append([]completionFlag(nil), s.Flags...)
	if s.Command != "completion" {
		for _, name := range completionCommonFlags {
			flags = append(flags, completionFlag{Name: name})
		}
	}
	return append(flags, completionFlag{Name: "--help"})
}

type completionScriptCommand struct {
	Name       string
	Flags      string
	ValueFlags string
	Positional string
	Words      string
	Max        int
	FlagValues []completionScriptValues
}

type completionScriptValues struct {
	Flag   string
	Values string
}

type completionScriptData struct {
	Commands    string
	TopFlags    string
	Specs       []completionScriptCommand
	HasFlagVals bool
}

func completionData() completionScriptData {
	data := completionScriptData{TopFlags: "--help --version"}
	var names []string
	for _, c := range commandSummaries {
		names = append(names, c.name)
		spec, ok := findCompletionSpec(c.name)
		if !ok {
			continue
		}
		item := completionScriptCommand{Name: c.name, Words: strings.Join(spec.Words, " ")}
		item.Positional = strings.Fields(spec.Positional + " ")[0]
		if i := strings.Index(item.Positional, ":"); i >= 0 {
			item.Positional = item.Positional[:i]
		}
		switch item.Positional {
		case "none":
			item.Max = 0
		case "paths":
			item.Max = -1
		default:
			item.Max = 1
		}
		var flags, valueFlags []string
		for _, f := range spec.allFlags() {
			flags = append(flags, f.Name)
			if f.takesValue() {
				valueFlags = append(valueFlags, f.Name)
			}
			if len(f.Values) > 0 {
				item.FlagValues = append(item.FlagValues, completionScriptValues{f.Name, strings.Join(f.Values, " ")})
			}
		}
		item.Flags = strings.Join(flags, " ")
		item.ValueFlags = strings.Join(valueFlags, " ")
		data.Specs = append(data.Specs, item)
	}
	data.Commands = strings.Join(names, " ")
	return data
}

var bashTemplate = template.Must(template.New("bash").Parse(`# bash completion for taskfactory and tf, generated by: taskfactory completion bash
_taskfactory() {
  local cur prev cmd="" word i dd=0 skip=0 npos=0 given=" " flags="" vflags="" pos="" max=0 avail f
  COMPREPLY=()
  cur=${COMP_WORDS[COMP_CWORD]}
  prev=""
  if (( COMP_CWORD > 0 )); then prev=${COMP_WORDS[COMP_CWORD-1]}; fi
  if (( COMP_CWORD == 1 )); then
    if [[ $cur == -* ]]; then
      COMPREPLY=($(compgen -W "{{.TopFlags}}" -- "$cur"))
    else
      COMPREPLY=($(compgen -W "{{.Commands}}" -- "$cur"))
    fi
    return 0
  fi
  for (( i=1; i<COMP_CWORD; i++ )); do
    word=${COMP_WORDS[i]}
    if [[ -z $cmd ]]; then
      if [[ $word != -* ]]; then cmd=$word; fi
      continue
    fi
    if (( skip )); then skip=0; continue; fi
    if (( dd )); then npos=$((npos+1)); continue; fi
    if [[ $word == -- ]]; then dd=1; continue; fi
    if [[ $word == -* ]]; then
      given+="$word "
      case "$cmd" in
{{- range .Specs}}
        {{.Name}}) vflags=" {{.ValueFlags}} ";;
{{- end}}
      esac
      if [[ $vflags == *" $word "* ]]; then skip=1; fi
    else
      npos=$((npos+1))
    fi
  done
  if [[ -z $cmd ]]; then return 0; fi
  case "$cmd" in
{{- range .Specs}}
    {{.Name}}) flags="{{.Flags}}"; vflags=" {{.ValueFlags}} "; pos={{.Positional}}; max={{.Max}};;
{{- end}}
    *) return 0;;
  esac
  if (( ! dd )) && [[ $vflags == *" $prev "* ]]; then
    case "$cmd $prev" in
{{- range .Specs}}{{$name := .Name}}{{range .FlagValues}}
      "{{$name}} {{.Flag}}") COMPREPLY=($(compgen -W "{{.Values}}" -- "$cur"));;
{{- end}}{{end}}
    esac
    return 0
  fi
  if (( ! dd )) && [[ $cur == -* ]]; then
    avail=""
    for f in $flags; do
      if [[ $given != *" $f "* ]]; then avail+="$f "; fi
    done
    COMPREPLY=($(compgen -W "$avail" -- "$cur"))
    return 0
  fi
  if (( max >= 0 && npos >= max )); then return 0; fi
  case "$pos" in
    ids)
      COMPREPLY=($(compgen -W "$("${COMP_WORDS[0]}" __complete ids "$cmd" "$cur" 2>/dev/null)" -- "$cur"))
      ;;
    path|paths)
      COMPREPLY=($(compgen -f -- "$cur"))
      compopt -o filenames 2>/dev/null || true
      ;;
    words)
      case "$cmd" in
{{- range .Specs}}{{if .Words}}
        {{.Name}}) COMPREPLY=($(compgen -W "{{.Words}}" -- "$cur"));;
{{- end}}{{end}}
      esac
      ;;
  esac
  return 0
}
complete -F _taskfactory taskfactory tf
`))

